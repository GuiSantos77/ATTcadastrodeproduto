CREATE DATABASE IF NOT EXISTS financeiro CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE financeiro;

CREATE TABLE IF NOT EXISTS produtos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    descricao VARCHAR(120) NOT NULL UNIQUE,
    categoria VARCHAR(40) NOT NULL,
    valor_compra DECIMAL(10,2) NOT NULL,
    valor_venda DECIMAL(10,2) NOT NULL,
    estoque INT UNSIGNED NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS vendas (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    produto_id INT UNSIGNED NULL,
    descricao VARCHAR(120) NOT NULL,
    quantidade INT UNSIGNED NOT NULL,
    valor_total DECIMAL(12,2) NOT NULL,
    lucro DECIMAL(12,2) NOT NULL,
    vendido_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_venda_produto FOREIGN KEY (produto_id)
        REFERENCES produtos (id) ON DELETE SET NULL
) ENGINE=InnoDB;
